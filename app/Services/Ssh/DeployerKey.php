<?php

namespace App\Services\Ssh;

use phpseclib3\Crypt\Common\PrivateKey;
use phpseclib3\Crypt\EC;
use phpseclib3\Crypt\PublicKeyLoader;
use RuntimeException;

/**
 * The ed25519 key pair ProxApps uses to log into freshly created containers.
 */
class DeployerKey
{
    public const COMMENT = 'proxapps-deployer';

    private ?PrivateKey $key = null;

    /** mtime/inode/size of the key file the cached key was read from (null = not from a file). */
    private ?string $stamp = null;

    public function __construct(private ?string $path = null) {}

    public function path(): string
    {
        return $this->path ?? (string) config('proxapps.ssh_key_path', storage_path('app/private/ssh/id_ed25519'));
    }

    /**
     * The cached key is re-read whenever the key file changed (e.g. regenerated by the web
     * process while a long-running queue worker still holds the old one).
     */
    public function privateKey(): PrivateKey
    {
        $path = $this->path();
        $stamp = $this->stamp($path);
        if ($this->key !== null && $stamp === $this->stamp) {
            return $this->key;
        }
        if ($stamp !== null) {
            $key = PublicKeyLoader::loadPrivateKey((string) file_get_contents($path));
            if (! $key instanceof PrivateKey) {
                throw new RuntimeException("{$path} enthält keinen privaten Schlüssel.");
            }
            $this->stamp = $stamp;

            return $this->key = $key;
        }
        $this->regenerate();

        return $this->key;
    }

    private function stamp(string $path): ?string
    {
        clearstatcache(true, $path);
        $st = @stat($path);
        if ($st === false || ! is_file($path)) {
            return null;
        }

        return $st['mtime'].':'.$st['ino'].':'.$st['size'];
    }

    public function publicKey(): string
    {
        return trim($this->privateKey()->getPublicKey()->toString('OpenSSH', ['comment' => self::COMMENT]));
    }

    public function regenerate(): void
    {
        $path = $this->path();
        $dir = dirname($path);
        if (! is_dir($dir) && ! mkdir($dir, 0700, true) && ! is_dir($dir)) {
            throw new RuntimeException("Verzeichnis {$dir} konnte nicht angelegt werden.");
        }
        @chmod($dir, 0700);

        /** @var PrivateKey $key */
        $key = EC::createKey('Ed25519');
        $tmp = $path.'.tmp';
        $old = umask(0077);
        try {
            if (file_put_contents($tmp, $key->toString('OpenSSH', ['comment' => self::COMMENT])) === false) {
                throw new RuntimeException("{$tmp} konnte nicht geschrieben werden.");
            }
            chmod($tmp, 0600);
            rename($tmp, $path);
        } finally {
            umask($old);
        }
        file_put_contents($path.'.pub', trim($key->getPublicKey()->toString('OpenSSH', ['comment' => self::COMMENT]))."\n");
        $this->key = $key;
        $this->stamp = $this->stamp($path);
    }
}
